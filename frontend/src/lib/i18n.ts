export type CopyKey = keyof (typeof dictionary)["en"];

export type Role = "admin" | "member" | "reader" | "hr" | "finance" | "engineering" | "legal" | "sales";

export function t(lang: Lang, key: CopyKey): string {
  return dictionary[lang][key] || dictionary.en[key];
}

export function statusLabel(lang: Lang, status: string): string {
  const key = `status_${status}` as CopyKey;
  if (key in dictionary.en) return t(lang, key);
  return status;
}

const PILL: Record<string, CopyKey> = {
  yonetim: "pillYonetim",
  hr: "pillHr",
  finance: "pillFinance",
  engineering: "pillEngineering",
  "islami-ilimler": "pillIslamic",
};

export function roomLabel(lang: Lang, slug: string, fallback = ""): string {
  const key = PILL[slug];
  return key ? t(lang, key) : fallback || slug;
}

export function navName(lang: Lang, user: { username?: string; full_name?: string; role?: string } | null): string {
  if (!user) return "";
  if (user.role === "admin" && (user.full_name === "Yönetici" || user.username === "admin")) return t(lang, "navAdmin");
  return user.full_name || "";
}

export function confidenceLabel(lang: Lang, label: string): string {
  const map: Record<string, CopyKey> = {
    High: "high",
    Medium: "medium",
    Low: "low",
    Weak: "weak",
  };
  const key = map[label];
  return key ? t(lang, key) : label;
}
